class InstructionType(Enum):
    """
    ## Assembly Instruction Classification

    We classify instructions by their primary purpose to support different
    types of analysis. This classification helps identify SIMD usage,
    performance characteristics, and optimization patterns.

    Note: Specific instruction patterns are now loaded from instructions.yaml
    rather than being hardcoded in Python.
    """

    SIMD_SSE = "simd_sse"          # SSE/SSE2/SSE3/SSE4 instructions
    SIMD_AVX = "simd_avx"          # AVX/AVX2 instructions
    SIMD_AVX512 = "simd_avx512"    # AVX-512 instructions
    MEMORY = "memory"              # Load/store operations
    ARITHMETIC = "arithmetic"      # Basic arithmetic operations
    CONTROL_FLOW = "control_flow"  # Jumps, calls, returns
    SYSTEM = "system"              # System calls, interrupts
    DATA = "data"                  # Data definitions and constants
    DIRECTIVE = "directive"        # Assembler directives
    UNKNOWN = "unknown"            # Unclassified instructions


class SectionType(Enum):
    """
    ## Assembly Section Types

    Different sections in assembly files serve different purposes.
    Understanding section types helps us focus analysis on the right parts.
    """

    TEXT = "text"          # Executable code
    DATA = "data"          # Initialized data
    BSS = "bss"            # Uninitialized data
    RODATA = "rodata"      # Read-only data
    DEBUG = "debug"        # Debug information
    OTHER = "other"        # Other sections


class InstructionClassifier:
    """
    ## Instruction Pattern Classification System

    Loads instruction patterns from external YAML configuration and provides
    classification services for assembly instructions. This replaces hardcoded
    instruction patterns with configurable, maintainable data files.
    """

    def __init__(self, config_path: Optional[Path] = None):
        """
        Initialize the instruction classifier.

        Args:
            config_path: Optional path to instructions.yaml file
        """
        if config_path is None:
            # Use default config path relative to this module
            config_dir = Path(__file__).parent.parent.parent / "config"
            config_path = config_dir / "instructions.yaml"

        self.config_path = config_path
        self._instruction_patterns: Optional[Dict[str, Any]] = None
        self._compiled_patterns: Dict[str, List[re.Pattern]] = {}

    @property
    def instruction_patterns(self) -> Dict[str, Any]:
        """Load instruction patterns on first access."""
        if self._instruction_patterns is None:
            self._load_patterns()
        return self._instruction_patterns

    def _load_patterns(self):
        """Load instruction patterns from YAML configuration."""
        try:
            with open(self.config_path, 'r', encoding='utf-8') as f:
                self._instruction_patterns = yaml.safe_load(f)
        except Exception as e:
            raise ValueError(f"Cannot load instruction patterns from {self.config_path}: {e}")

    def classify_instruction(self, opcode: str, operands: List[str]) -> Tuple[InstructionType, bool, Optional[int]]:
        """
        ## Classify Instruction

        Classify an instruction by opcode and operands, determining its type,
        whether it's SIMD, and register width for SIMD instructions.

        Args:
            opcode: Instruction mnemonic
            operands: List of instruction operands

        Returns:
            Tuple of (instruction_type, is_simd, register_width)
        """
        if not opcode:
            return InstructionType.DIRECTIVE, False, None

        opcode_lower = opcode.lower()

        # Check each instruction type
        for type_name, type_info in self.instruction_patterns.get('instruction_types', {}).items():
            if self._matches_patterns(opcode_lower, type_info.get('patterns', [])):
                instruction_type = self._get_instruction_type_enum(type_name)
                is_simd = type_name.startswith('simd_')
                register_width = None

                if is_simd:
                    register_width = self._determine_register_width(operands, type_info.get('register_widths', []))

                return instruction_type, is_simd, register_width

        return InstructionType.UNKNOWN, False, None

    def _matches_patterns(self, opcode: str, patterns: List[str]) -> bool:
        """Check if opcode matches any of the given patterns."""
        for pattern in patterns:
            if self._match_pattern(opcode, pattern):
                return True
        return False

    def _match_pattern(self, opcode: str, pattern: str) -> bool:
        """Match a single pattern against an opcode."""
        pattern_lower = pattern.lower()

        # Exact match
        if opcode == pattern_lower:
            return True

        # Prefix match for instruction families
        if self.instruction_patterns.get('compilation', {}).get('prefix_matching', True):
            if opcode.startswith(pattern_lower):
                return True

        return False

    def _get_instruction_type_enum(self, type_name: str) -> InstructionType:
        """Convert string type name to InstructionType enum."""
        type_mapping = {
            'simd_sse': InstructionType.SIMD_SSE,
            'simd_avx': InstructionType.SIMD_AVX,
            'simd_avx512': InstructionType.SIMD_AVX512,
            'memory': InstructionType.MEMORY,
            'arithmetic': InstructionType.ARITHMETIC,
            'control_flow': InstructionType.CONTROL_FLOW,
            'system': InstructionType.SYSTEM,
        }
        return type_mapping.get(type_name, InstructionType.UNKNOWN)

    def _determine_register_width(self, operands: List[str], possible_widths: List[int]) -> Optional[int]:
        """Determine register width from operands."""
        for operand in operands:
            operand_lower = operand.lower()

            # Check for specific register patterns
            if any(reg in operand_lower for reg in ['zmm', 'k0', 'k1', 'k2', 'k3', 'k4', 'k5', 'k6', 'k7']):
                return 512
            elif 'ymm' in operand_lower:
                return 256
            elif 'xmm' in operand_lower:
                return 128

        # Return default width for this instruction type
        if possible_widths:
            return max(possible_widths)  # Use largest available width as default

        return None


# Global classifier instance
_global_classifier: Optional[InstructionClassifier] = None

def get_instruction_classifier() -> InstructionClassifier:
    """Get the global instruction classifier instance."""
    global _global_classifier
    if _global_classifier is None:
        _global_classifier = InstructionClassifier()
    return _global_classifier


@dataclass
class AssemblyInstruction:
    """
    ## Individual Assembly Instruction

    Represents a single assembly instruction with its components parsed
    and classified. This allows for precise analysis of instruction usage
    patterns and SIMD detection.

    ### Design Notes

    We separate the raw line from the parsed components to preserve the
    original formatting while enabling programmatic analysis. The
    instruction_type classification supports high-level analysis without
    needing to re-parse opcodes constantly.
    """

    # Raw instruction as it appears in the file
    raw_line: str
    line_number: int

    # Parsed components
    label: Optional[str] = None       # Optional label on this line
    opcode: Optional[str] = None      # Instruction mnemonic (e.g., "movq")
    operands: List[str] = field(default_factory=list)  # Instruction arguments
    comment: Optional[str] = None     # End-of-line comment

    # Classification and analysis
    instruction_type: InstructionType = InstructionType.UNKNOWN
    is_simd: bool = False
    register_width: Optional[int] = None  # 128, 256, 512 for SIMD instructions

    def __post_init__(self):
        """Classify the instruction after creation."""
        self._classify_instruction()

    def _classify_instruction(self):
        """
        ## Instruction Classification

        Analyze the opcode to determine instruction type and SIMD characteristics.
        This classification now uses external YAML configuration instead of
        hardcoded patterns, making it maintainable and extensible.
        """

        try:
            classifier = get_instruction_classifier()
            self.instruction_type, self.is_simd, self.register_width = classifier.classify_instruction(
                self.opcode or "", self.operands
            )
        except Exception:
            # Fallback to unknown classification if external config fails
            self.instruction_type = InstructionType.UNKNOWN
            self.is_simd = False
            self.register_width = None

    def matches_pattern(self, pattern: str) -> bool:
        """
        ## Pattern Matching

        Check if this instruction matches a given pattern. Patterns can be:
        - Exact opcode match: "movdqa"
        - Regex pattern: r"mov.*"
        - Instruction type: "simd", "memory", etc.

        Args:
            pattern: Pattern to match against

        Returns:
            True if the instruction matches the pattern
        """

        pattern_lower = pattern.lower()

        # Check instruction type shortcuts
        if pattern_lower == "simd" and self.is_simd:
            return True
        if pattern_lower == self.instruction_type.value:
            return True

        # Check exact opcode match
        if self.opcode and pattern_lower == self.opcode.lower():
            return True

        # Use classifier for pattern matching
        try:
            classifier = get_instruction_classifier()
            if self.opcode:
                return classifier._match_pattern(self.opcode.lower(), pattern)
        except Exception:
            # Fallback to simple string matching
            if self.opcode and pattern_lower in self.opcode.lower():
                return True

        return False


@dataclass
class AssemblyFunction:
    """
    ## Assembly Function Representation

    Represents a complete function extracted from assembly code, including
    all its instructions, labels, and metadata. This is the primary unit
    of analysis for SIMD detection and performance analysis.

    ### Function Boundary Detection

    Function boundaries are detected using multiple heuristics:
    - Function labels (name followed by colon)
    - Size directives (.size symbol, expression)
    - Control flow analysis (ret instructions)
    - Symbol table information when available

    ### Analysis Capabilities

    Each function can be analyzed for:
    - SIMD instruction usage and types
    - Register usage patterns
    - Control flow complexity
    - Memory access patterns
    """

    name: str
    start_line: int
    end_line: int

    # Function content
    instructions: List[AssemblyInstruction] = field(default_factory=list)
    labels: List[str] = field(default_factory=list)  # Internal labels within function

    # Metadata
    size_bytes: Optional[int] = None
    section: SectionType = SectionType.TEXT

    # Analysis results (computed lazily)
    _simd_analysis: Optional[Dict[str, Any]] = field(default=None, init=False)
    _instruction_stats: Optional[Dict[str, int]] = field(default=None, init=False)

    @property
    def instruction_count(self) -> int:
        """Get the total number of instructions in this function."""
        return len([inst for inst in self.instructions if inst.opcode is not None])

    @property
    def simd_instruction_count(self) -> int:
        """Get the number of SIMD instructions in this function."""
        return len([inst for inst in self.instructions if inst.is_simd])

    @property
    def has_simd(self) -> bool:
        """Check if this function contains any SIMD instructions."""
        return self.simd_instruction_count > 0

    def get_simd_analysis(self) -> Dict[str, Any]:
        """
        ## SIMD Analysis

        Perform comprehensive analysis of SIMD instruction usage in this function.
        Results are cached after first computation.

        Returns:
            Dictionary with SIMD analysis results including:
            - instruction_types: Count by SIMD type (SSE, AVX, AVX-512)
            - register_widths: Count by register width (128, 256, 512)
            - unique_opcodes: Set of unique SIMD opcodes used
            - simd_percentage: Percentage of instructions that are SIMD
        """

        if self._simd_analysis is None:
            self._compute_simd_analysis()
        return self._simd_analysis

    def _compute_simd_analysis(self):
        """Compute SIMD analysis and cache the results."""

        analysis = {
            'instruction_types': defaultdict(int),
            'register_widths': defaultdict(int),
            'unique_opcodes': set(),
            'simd_percentage': 0.0,
            'total_instructions': self.instruction_count,
            'simd_instructions': self.simd_instruction_count
        }

        for instruction in self.instructions:
            if instruction.is_simd:
                analysis['instruction_types'][instruction.instruction_type.value] += 1
                if instruction.register_width:
                    analysis['register_widths'][instruction.register_width] += 1
                if instruction.opcode:
                    analysis['unique_opcodes'].add(instruction.opcode.lower())

        # Convert unique opcodes set to sorted list for JSON serialization
        analysis['unique_opcodes'] = sorted(list(analysis['unique_opcodes']))

        # Calculate SIMD percentage
        if analysis['total_instructions'] > 0:
            analysis['simd_percentage'] = (analysis['simd_instructions'] /
                                         analysis['total_instructions']) * 100

        # Convert defaultdicts to regular dicts
        analysis['instruction_types'] = dict(analysis['instruction_types'])
        analysis['register_widths'] = dict(analysis['register_widths'])

        self._simd_analysis = analysis

    def get_instructions_matching(self, pattern: str) -> List[AssemblyInstruction]:
        """
        ## Pattern-Based Instruction Filtering

        Get all instructions in this function that match a given pattern.
        This enables flexible analysis of specific instruction types or patterns.

        Args:
            pattern: Pattern to match (opcode, regex, or instruction type)

        Returns:
            List of matching instructions
        """

        return [inst for inst in self.instructions if inst.matches_pattern(pattern)]

    def get_instruction_stats(self) -> Dict[str, int]:
        """
        ## Instruction Statistics

        Get comprehensive statistics about instruction usage in this function.
        Results are cached after first computation.

        Returns:
            Dictionary with instruction statistics by type and opcode
        """

        if self._instruction_stats is None:
            self._compute_instruction_stats()
        return self._instruction_stats

    def _compute_instruction_stats(self):
        """Compute instruction statistics and cache the results."""

        stats = {
            'total_instructions': 0,
            'by_type': defaultdict(int),
            'by_opcode': defaultdict(int),
            'unique_opcodes': set()
        }

        for instruction in self.instructions:
            if instruction.opcode:
                stats['total_instructions'] += 1
                stats['by_type'][instruction.instruction_type.value] += 1
                stats['by_opcode'][instruction.opcode.lower()] += 1
                stats['unique_opcodes'].add(instruction.opcode.lower())

        # Convert to regular dicts and sorted lists
        stats['by_type'] = dict(stats['by_type'])
        stats['by_opcode'] = dict(stats['by_opcode'])
        stats['unique_opcodes'] = sorted(list(stats['unique_opcodes']))

        self._instruction_stats = stats

    def to_assembly_text(self, include_labels: bool = True,
                        include_comments: bool = True) -> str:
        """
        ## Export Function as Assembly Text

        Convert this function back to assembly text format. This enables
        selective extraction of functions from large assembly files.

        Args:
            include_labels: Whether to include internal labels
            include_comments: Whether to include comments

        Returns:
            Assembly text representation of this function
        """

        lines = []

        # Add function label
        lines.append(f"{self.name}:")

        # Add instructions
        for instruction in self.instructions:
            line = instruction.raw_line

            if not include_comments and instruction.comment:
                # Strip comments if requested
                comment_pos = line.rfind('#')
                if comment_pos >= 0:
                    line = line[:comment_pos].rstrip()

            if include_labels or not instruction.label:
                lines.append(line)

        return '\n'.join(lines)


@dataclass
class AssemblySection:
    """
    ## Assembly Section Representation

    Represents a section of assembly code that isn't part of a function,
    such as data sections, debug information, or other directives.

    ### Purpose

    While our primary focus is on function analysis, we need to handle
    non-function content appropriately to avoid parsing errors and to
    provide complete file representation when needed.
    """

    name: str
    section_type: SectionType
    start_line: int
    end_line: int
    raw_content: List[str] = field(default_factory=list)

    @property
    def size_lines(self) -> int:
        """Get the size of this section in lines."""
        return len(self.raw_content)


class AssemblyParser:
    """
    ## Assembly File Parser

    Parses assembly files into structured representations. The parser handles
    the complexity of detecting function boundaries, classifying instructions,
    and organizing content into analyzable structures.

    ### Parsing Strategy

    The parser uses a multi-pass approach:
    1. **First pass**: Identify major sections and function boundaries
    2. **Second pass**: Parse individual instructions and classify them
    3. **Third pass**: Build relationships and compute metadata

    This approach ensures accurate function boundary detection even in
    complex assembly files with embedded data and multiple sections.

    ### Design Philosophy

    - **Conservative**: When in doubt, include more context rather than less
    - **Robust**: Handle various assembly formats and compiler outputs
    - **Streaming**: Process large files without excessive memory usage
    - **Structured**: Build rich object model for programmatic analysis
    """

    def __init__(self):
        """Initialize the assembly parser with default settings."""

        # Function detection patterns
        self.function_label_pattern = re.compile(r'^([a-zA-Z_][a-zA-Z0-9_.$]*):')
        self.size_directive_pattern = re.compile(r'\.size\s+([^,]+),\s*(.+)')

        # Section patterns
        self.section_pattern = re.compile(r'\.section\s+([^,]+)')

        # Instruction parsing patterns
        self.instruction_pattern = re.compile(
            r'^\s*'                    # Optional whitespace
            r'(?:([a-zA-Z_][a-zA-Z0-9_.$]*):)?'  # Optional label
            r'\s*'                     # Whitespace
            r'(?:([a-zA-Z][a-zA-Z0-9]*)\s*'      # Opcode
            r'([^#]*?))?'              # Operands (non-greedy)
            r'(?:#(.*))?'              # Optional comment
            r'$'                       # End of line
        )

    def parse_file(self, file_path: Path) -> 'AssemblyFile':
        """
        ## Parse Assembly File

        Parse a complete assembly file into structured representation.
        This is the main entry point for assembly processing.

        Args:
            file_path: Path to the assembly file to parse

        Returns:
            AssemblyFile object with parsed content

        Raises:
            FileNotFoundError: If the assembly file doesn't exist
            ValueError: If the file cannot be parsed
        """

        if not file_path.exists():
            raise FileNotFoundError(f"Assembly file not found: {file_path}")

        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                lines = f.readlines()
        except Exception as e:
            raise ValueError(f"Cannot read assembly file {file_path}: {e}")

        return self._parse_lines(lines, file_path)

    def parse_text(self, assembly_text: str, name: str = "assembly") -> 'AssemblyFile':
        """
        ## Parse Assembly Text

        Parse assembly text directly without reading from file.
        Useful for testing and processing generated assembly.

        Args:
            assembly_text: Assembly text to parse
            name: Name to use for the assembly file

        Returns:
            AssemblyFile object with parsed content
        """

        lines = assembly_text.split('\n')
        return self._parse_lines(lines, Path(name))

    def _parse_lines(self, lines: List[str], source_path: Path) -> 'AssemblyFile':
        """
        ## Core Parsing Logic

        Process lines of assembly code into structured representation.
        This implements the multi-pass parsing strategy.

        Args:
            lines: Lines of assembly code
            source_path: Source file path for metadata

        Returns:
            Parsed AssemblyFile object
        """

        # Initialize assembly file
        assembly_file = AssemblyFile(
            path=source_path,
            total_lines=len(lines)
        )

        # First pass: Identify functions and major structures
        function_boundaries = self._identify_functions(lines)

        # Second pass: Parse functions and their instructions
        for func_name, start_line, end_line in function_boundaries:
            function = self._parse_function(func_name, start_line, end_line, lines)
            assembly_file.functions[func_name] = function

        # Third pass: Handle remaining content as sections
        self._parse_sections(lines, function_boundaries, assembly_file)

        return assembly_file

    def _identify_functions(self, lines: List[str]) -> List[Tuple[str, int, int]]:
        """
        ## Function Boundary Detection

        Identify function boundaries using multiple heuristics to ensure
        accurate extraction even from complex assembly files.

        Args:
            lines: Assembly file lines

        Returns:
            List of (function_name, start_line, end_line) tuples
        """

        functions = []
        current_function = None

        for line_num, line in enumerate(lines):
            line = line.strip()

            # Skip empty lines and comments
            if not line or line.startswith('#'):
                continue

            # Check for function label
            label_match = self.function_label_pattern.match(line)
            if label_match:
                label_name = label_match.group(1)

                # Filter out likely data labels and internal labels
                if self._is_likely_function_label(label_name, lines, line_num):
                    # Close previous function if open
                    if current_function:
                        functions.append((current_function[0], current_function[1], line_num - 1))

                    # Start new function
                    current_function = (label_name, line_num)

            # Check for size directive (marks end of function)
            elif line.startswith('.size') and current_function:
                size_match = self.size_directive_pattern.match(line)
                if size_match and size_match.group(1).strip() == current_function[0]:
                    functions.append((current_function[0], current_function[1], line_num))
                    current_function = None

        # Close final function if still open
        if current_function:
            functions.append((current_function[0], current_function[1], len(lines) - 1))

        return functions

    def _is_likely_function_label(self, label_name: str, lines: List[str], line_num: int) -> bool:
        """
        ## Function Label Classification

        Determine if a label is likely to be a function rather than data or
        an internal label. Uses heuristics based on naming patterns and
        surrounding context.

        Args:
            label_name: The label name to classify
            lines: All assembly lines (for context)
            line_num: Line number of the label

        Returns:
            True if this is likely a function label
        """

        # Skip obvious data labels
        if any(keyword in label_name.lower() for keyword in
               ['.str', '.data', '.rodata', '.bss', '.debug', '.eh_frame']):
            return False

        # Skip very short labels (likely internal)
        if len(label_name) < 3:
            return False

        # Look at following lines for function-like content
        lookahead_lines = 5
        has_instructions = False

        for i in range(line_num + 1, min(line_num + lookahead_lines, len(lines))):
            line = lines[i].strip()
            if not line or line.startswith('#'):
                continue

            # Look for typical function prologue or instructions
            if any(instr in line.lower() for instr in
                   ['push', 'mov', 'sub', 'call', 'ret', 'jmp']):
                has_instructions = True
                break

            # Stop if we hit another label or directive
            if line.endswith(':') or line.startswith('.'):
                break

        return has_instructions

    def _parse_function(self, func_name: str, start_line: int, end_line: int,
                       lines: List[str]) -> AssemblyFunction:
        """
        ## Function Parsing

        Parse a single function from its line range, extracting all
        instructions and building the structured representation.

        Args:
            func_name: Name of the function
            start_line: Starting line number (inclusive)
            end_line: Ending line number (inclusive)
            lines: All assembly lines

        Returns:
            Parsed AssemblyFunction object
        """

        function = AssemblyFunction(
            name=func_name,
            start_line=start_line,
            end_line=end_line
        )

        # Parse each line in the function
        for line_num in range(start_line, min(end_line + 1, len(lines))):
            raw_line = lines[line_num].rstrip('\n\r')

            # Skip the function label line itself
            if line_num == start_line:
                continue

            # Parse the instruction
            instruction = self._parse_instruction(raw_line, line_num)
            function.instructions.append(instruction)

            # Collect internal labels
            if instruction.label and instruction.label != func_name:
                function.labels.append(instruction.label)

        return function

    def _parse_instruction(self, raw_line: str, line_num: int) -> AssemblyInstruction:
        """
        ## Instruction Parsing

        Parse a single line of assembly into a structured instruction
        representation with all components identified.

        Args:
            raw_line: Raw assembly line
            line_num: Line number in source file

        Returns:
            Parsed AssemblyInstruction object
        """

        instruction = AssemblyInstruction(
            raw_line=raw_line,
            line_number=line_num
        )

        # Parse instruction components using regex
        match = self.instruction_pattern.match(raw_line)
        if match:
            instruction.label = match.group(1)
            instruction.opcode = match.group(2)

            # Parse operands
            operands_str = match.group(3)
            if operands_str:
                # Split operands by comma, handling nested parentheses
                instruction.operands = self._parse_operands(operands_str.strip())

            # Extract comment
            instruction.comment = match.group(4)
            if instruction.comment:
                instruction.comment = instruction.comment.strip()

        return instruction

    def _parse_operands(self, operands_str: str) -> List[str]:
        """
        ## Operand Parsing

        Parse instruction operands, handling complex cases like nested
        parentheses and memory addressing modes.

        Args:
            operands_str: String containing all operands

        Returns:
            List of individual operands
        """

        operands = []
        current_operand = ""
        paren_count = 0

        for char in operands_str:
            if char == '(':
                paren_count += 1
                current_operand += char
            elif char == ')':
                paren_count -= 1
                current_operand += char
            elif char == ',' and paren_count == 0:
                # Comma at top level - end of operand
                operands.append(current_operand.strip())
                current_operand = ""
            else:
                current_operand += char

        # Add final operand
        if current_operand.strip():
            operands.append(current_operand.strip())

        return operands

    def _parse_sections(self, lines: List[str], function_boundaries: List[Tuple[str, int, int]],
                       assembly_file: 'AssemblyFile'):
        """
        ## Section Parsing

        Parse non-function content into section objects. This handles
        data sections, debug information, and other assembly directives.

        Args:
            lines: All assembly lines
            function_boundaries: List of (name, start, end) for functions
            assembly_file: AssemblyFile to add sections to
        """

        # Create set of function line ranges for easy lookup
        function_lines = set()
        for _, start, end in function_boundaries:
            function_lines.update(range(start, end + 1))

        # Process non-function lines
        current_section = None
        section_start = None

        for line_num, line in enumerate(lines):
            if line_num in function_lines:
                continue  # Skip function content

            line = line.strip()
            if not line:
                continue

            # Check for section directive
            section_match = self.section_pattern.match(line)
            if section_match:
                # Close previous section
                if current_section:
                    assembly_file.sections[current_section] = AssemblySection(
                        name=current_section,
                        section_type=self._classify_section_type(current_section),
                        start_line=section_start,
                        end_line=line_num - 1,
                        raw_content=lines[section_start:line_num]
                    )

                # Start new section
                current_section = section_match.group(1).strip()
                section_start = line_num

        # Close final section
        if current_section and section_start is not None:
            assembly_file.sections[current_section] = AssemblySection(
                name=current_section,
                section_type=self._classify_section_type(current_section),
                start_line=section_start,
                end_line=len(lines) - 1,
                raw_content=lines[section_start:]
            )

    def _classify_section_type(self, section_name: str) -> SectionType:
        """
        ## Section Type Classification

        Classify assembly sections by their purpose based on name patterns.

        Args:
            section_name: Name of the section

        Returns:
            Classified SectionType
        """

        name_lower = section_name.lower()

        if 'text' in name_lower:
            return SectionType.TEXT
        elif 'data' in name_lower:
            return SectionType.DATA
        elif 'bss' in name_lower:
            return SectionType.BSS
        elif 'rodata' in name_lower or 'const' in name_lower:
            return SectionType.RODATA
        elif 'debug' in name_lower:
            return SectionType.DEBUG
        else:
            return SectionType.OTHER


@dataclass
class AssemblyFile:
    """
    ## Complete Assembly File Representation

    Top-level container for a parsed assembly file. Provides high-level
    analysis capabilities and export functionality.

    ### Usage Philosophy

    The AssemblyFile serves as the main interface for assembly analysis.
    Users typically load a file, then query it for specific functions
    or instruction patterns without needing to understand the internal
    parsing details.

    ### Analysis Capabilities

    - Function-level SIMD analysis
    - Cross-function pattern matching
    - Export of filtered subsets
    - Summary statistics and reporting
    """

    path: Path
    total_lines: int
    parse_time: Optional[float] = None

    # Parsed content
    functions: Dict[str, AssemblyFunction] = field(default_factory=dict)
    sections: Dict[str, AssemblySection] = field(default_factory=dict)

    # Cached analysis results
    _global_analysis: Optional[Dict[str, Any]] = field(default=None, init=False)

    @property
    def function_count(self) -> int:
        """Get the number of functions in this file."""
        return len(self.functions)

    @property
    def functions_with_simd(self) -> List[str]:
        """Get names of functions that contain SIMD instructions."""
        return [name for name, func in self.functions.items() if func.has_simd]

    def get_function(self, name: str) -> Optional[AssemblyFunction]:
        """Get a specific function by name."""
        return self.functions.get(name)

    def get_functions_matching(self, pattern: str) -> Dict[str, AssemblyFunction]:
        """
        ## Function Name Pattern Matching

        Get all functions whose names match a given pattern.

        Args:
            pattern: Pattern to match against function names (regex supported)

        Returns:
            Dictionary of matching functions
        """

        matching = {}

        try:
            regex_pattern = re.compile(pattern, re.IGNORECASE)
            for name, func in self.functions.items():
                if regex_pattern.search(name):
                    matching[name] = func
        except re.error:
            # Fallback to simple string matching
            pattern_lower = pattern.lower()
            for name, func in self.functions.items():
                if pattern_lower in name.lower():
                    matching[name] = func

        return matching

    def get_functions_with_instruction_pattern(self, pattern: str) -> Dict[str, AssemblyFunction]:
        """
        ## Instruction Pattern Matching

        Get all functions that contain instructions matching a given pattern.

        Args:
            pattern: Instruction pattern to match

        Returns:
            Dictionary of functions containing matching instructions
        """

        matching = {}

        for name, func in self.functions.items():
            if func.get_instructions_matching(pattern):
                matching[name] = func

        return matching

    def export_functions(self, function_names: List[str],
                        output_path: Optional[Path] = None) -> str:
        """
        ## Export Selected Functions

        Export specified functions as assembly text. This enables selective
        extraction from large assembly files.

        Args:
            function_names: List of function names to export
            output_path: Optional path to write output file

        Returns:
            Assembly text for the selected functions
        """

        output_lines = []

        for func_name in function_names:
            func = self.functions.get(func_name)
            if func:
                output_lines.append(func.to_assembly_text())
                output_lines.append("")  # Blank line between functions

        result = "\n".join(output_lines)

        if output_path:
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write(result)

        return result

    def get_global_analysis(self) -> Dict[str, Any]:
        """
        ## Global Assembly Analysis

        Perform comprehensive analysis across all functions in the file.
        Results are cached after first computation.

        Returns:
            Dictionary with global analysis results
        """

        if self._global_analysis is None:
            self._compute_global_analysis()
        return self._global_analysis

    def _compute_global_analysis(self):
        """Compute global analysis and cache the results."""

        analysis = {
            'total_functions': len(self.functions),
            'functions_with_simd': len(self.functions_with_simd),
            'simd_usage_percentage': 0.0,
            'instruction_type_summary': defaultdict(int),
            'simd_type_summary': defaultdict(int),
            'top_functions_by_simd': []
        }

        total_instructions = 0
        total_simd_instructions = 0

        function_simd_stats = []

        for func_name, func in self.functions.items():
            func_stats = func.get_instruction_stats()
            simd_analysis = func.get_simd_analysis()

            total_instructions += func_stats['total_instructions']
            total_simd_instructions += simd_analysis['simd_instructions']

            # Accumulate instruction type counts
            for inst_type, count in func_stats['by_type'].items():
                analysis['instruction_type_summary'][inst_type] += count

            # Accumulate SIMD type counts
            for simd_type, count in simd_analysis['instruction_types'].items():
                analysis['simd_type_summary'][simd_type] += count

            # Track function SIMD stats for ranking
            if simd_analysis['simd_instructions'] > 0:
                function_simd_stats.append((
                    func_name,
                    simd_analysis['simd_instructions'],
                    simd_analysis['simd_percentage']
                ))

        # Calculate global SIMD usage percentage
        if total_instructions > 0:
            analysis['simd_usage_percentage'] = (total_simd_instructions / total_instructions) * 100

        # Sort functions by SIMD usage
        function_simd_stats.sort(key=lambda x: x[1], reverse=True)
        analysis['top_functions_by_simd'] = function_simd_stats[:10]  # Top 10

        # Convert defaultdicts to regular dicts
        analysis['instruction_type_summary'] = dict(analysis['instruction_type_summary'])
        analysis['simd_type_summary'] = dict(analysis['simd_type_summary'])

        self._global_analysis = analysis


# Analysis integration functions

def create_simd_analysis_report(assembly_file: AssemblyFile,
                              target_name: str = "unknown") -> Dict[str, Any]:
    """
    ## Create Comprehensive SIMD Analysis Report

    Generate a complete SIMD analysis report for an assembly file using
    the centralized instruction patterns. This integrates with the
    benchmark orchestration system.

    Args:
        assembly_file: Parsed assembly file
        target_name: Name of the compilation target

    Returns:
        Dictionary with comprehensive SIMD analysis
    """

    global_analysis = assembly_file.get_global_analysis()

    # Get instruction classifier for pattern details
    try:
        classifier = get_instruction_classifier()
        instruction_config = classifier.instruction_patterns

        # Extract quick detection patterns for summary
        quick_patterns = instruction_config.get('analysis_settings', {}).get('quick_simd_patterns', [])
        optimization_indicators = instruction_config.get('analysis_settings', {}).get('optimization_indicators', [])

        # Count functions matching optimization patterns
        optimized_functions = 0
        for func_name, func in assembly_file.functions.items():
            for pattern in optimization_indicators:
                if func.get_instructions_matching(pattern):
                    optimized_functions += 1
                    break

        # Enhanced report with pattern-based insights
        report = {
            'target_name': target_name,
            'analysis_timestamp': datetime.now(timezone.utc).isoformat(),
            'global_analysis': global_analysis,
            'pattern_analysis': {
                'quick_simd_detected': any(
                    assembly_file.get_functions_with_instruction_pattern(pattern)
                    for pattern in quick_patterns
                ),
                'optimized_functions': optimized_functions,
                'optimization_percentage': (optimized_functions / len(assembly_file.functions) * 100) if assembly_file.functions else 0
            },
            'instruction_config_version': instruction_config.get('metadata', {}).get('version', 'unknown')
        }

    except Exception:
        # Fallback to basic analysis if config loading fails
        report = {
            'target_name': target_name,
            'analysis_timestamp': datetime.now(timezone.utc).isoformat(),
            'global_analysis': global_analysis,
            'pattern_analysis': {
                'quick_simd_detected': len(assembly_file.functions_with_simd) > 0,
                'optimized_functions': len(assembly_file.functions_with_simd),
                'optimization_percentage': (len(assembly_file.functions_with_simd) / len(assembly_file.functions) * 100) if assembly_file.functions else 0
            },
            'instruction_config_version': 'fallback'
        }

    return report


def extract_benchmark_functions(file_path: Path,
                               function_patterns: List[str] = None) -> Dict[str, str]:
    """
    ## Extract Benchmark Functions

    Extract specific functions from assembly files using configurable patterns.
    This is designed for the benchmark orchestration system to extract
    core benchmark functions from large assembly files.

    Args:
        file_path: Path to assembly file
        function_patterns: List of function name patterns (default: find_all patterns)

    Returns:
        Dictionary mapping function names to their assembly text
    """

    if function_patterns is None:
        function_patterns = [r".*find_all.*", r".*benchmark.*"]

    assembly = load_assembly_file(file_path)
    extracted_functions = {}

    for pattern in function_patterns:
        matching_functions = assembly.get_functions_matching(pattern)
        for func_name, func in matching_functions.items():
            extracted_functions[func_name] = func.to_assembly_text(
                include_labels=True,
                include_comments=False  # Clean output for analysis
            )

    return extracted_functions


# High-level convenience functions

def load_assembly_file(file_path: Path) -> AssemblyFile:
    """
    ## Load Assembly File

    High-level function to load and parse an assembly file.
    This is the main entry point for most users.

    Args:
        file_path: Path to assembly file

    Returns:
        Parsed AssemblyFile object

    Example:
        ```python
        from benchfind.assembly import load_assembly_file

        asm = load_assembly_file(Path("benchmark.s"))
        simd_functions = asm.functions_with_simd
        ```
    """

    import time
    start_time = time.time()

    parser = AssemblyParser()
    assembly_file = parser.parse_file(file_path)

    assembly_file.parse_time = time.time() - start_time
    return assembly_file


def extract_functions_by_pattern(file_path: Path, pattern: str,
                                output_path: Optional[Path] = None) -> str:
    """
    ## Extract Functions by Pattern

    Extract functions matching a name pattern from an assembly file.
    This is useful for focusing analysis on specific functions.

    Args:
        file_path: Path to source assembly file
        pattern: Pattern to match function names
        output_path: Optional output file path

    Returns:
        Assembly text for matching functions

    Example:
        ```python
        # Extract all find_all functions
        result = extract_functions_by_pattern(
            Path("benchmark.s"),
            r".*find_all.*",
            Path("find_all_functions.s")
        )
        ```
    """

    assembly = load_assembly_file(file_path)
    matching_functions = assembly.get_functions_matching(pattern)
    return assembly.export_functions(list(matching_functions.keys()), output_path)


def analyze_simd_usage(file_path: Path) -> Dict[str, Any]:
    """
    ## Analyze SIMD Usage

    Perform comprehensive SIMD analysis on an assembly file.
    This provides a high-level summary of SIMD instruction usage.

    Args:
        file_path: Path to assembly file to analyze

    Returns:
        Dictionary with SIMD analysis results

    Example:
        ```python
        analysis = analyze_simd_usage(Path("benchmark.s"))
        print(f"SIMD usage: {analysis['simd_usage_percentage']:.1f}%")
        print(f"Functions with SIMD: {analysis['functions_with_simd']}")
        ```
    """

    assembly = load_assembly_file(file_path)
    return assembly.get_global_analysis()


class AssemblyAnalyzer:
    """
    ## High-Level Assembly Analysis Orchestrator

    Provides a high-level interface for assembly generation, parsing, and analysis.
    This class coordinates the various assembly processing components to provide
    comprehensive analysis capabilities.
    """

    def __init__(self, config: Dict[str, Any], console):
        """Initialize the assembly analyzer."""
        self.config = config
        self.console = console

    def generate_and_analyze_target(self, target: 'TargetDefinition', output_dir: Path, project_root: Path) -> Dict[str, Any]:
        """
        Generate assembly for a target and perform comprehensive analysis.

        Args:
            target: Target definition to generate assembly for
            output_dir: Directory to store assembly files
            project_root: Root of the Rust project

        Returns:
            Dictionary containing analysis results
        """
        import subprocess
        import os

        self.console.print(f"[blue]🔬 Generating assembly for target {target.name}[/blue]")

        # Create output directory
        output_dir.mkdir(parents=True, exist_ok=True)

        # Set up environment for compilation
        env = os.environ.copy()
        if hasattr(target, 'rustflags') and target.rustflags:
            env['RUSTFLAGS'] = target.rustflags

        # Generate assembly using cargo
        try:
            cmd = [
                'cargo', 'rustc', '--release', '--',
                '--emit=asm', '-C', 'opt-level=3'
            ]

            result = subprocess.run(
                cmd,
                cwd=project_root,
                env=env,
                capture_output=True,
                text=True,
                timeout=300  # 5 minute timeout
            )

            if result.returncode != 0:
                raise RuntimeError(f"Assembly generation failed: {result.stderr}")

            # Find generated assembly files
            assembly_files = list((project_root / "target" / "release" / "deps").glob("*.s"))

            if not assembly_files:
                raise RuntimeError("No assembly files generated")

            # Copy and analyze the main assembly file
            main_assembly = assembly_files[0]  # Take the first one
            target_assembly = output_dir / f"{target.name}_complete.s"

            # Copy assembly file
            import shutil
            shutil.copy2(main_assembly, target_assembly)

            # Perform SIMD analysis
            simd_analysis = analyze_simd_usage(target_assembly)

            # Save analysis results
            analysis_file = output_dir / "simd_analysis.json"
            import json
            with open(analysis_file, 'w') as f:
                json.dump(simd_analysis, f, indent=2, default=str)

            self.console.print(f"[green]✅ Assembly analysis completed for {target.name}[/green]")

            return {
                'target': target.name,
                'assembly_file': str(target_assembly),
                'analysis_file': str(analysis_file),
                'simd_detected': simd_analysis.get('simd_usage_percentage', 0) > 0,
                'simd_percentage': simd_analysis.get('simd_usage_percentage', 0)
            }

        except Exception as e:
            self.console.print(f"[red]❌ Assembly analysis failed for {target.name}: {e}[/red]")
            raise
